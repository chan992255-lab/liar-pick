export function foolWordFor(categoryId: string, word: string): string {
  const mapped = SIMILAR[word];
  if (mapped) return mapped;
  const category = CATEGORY_MAP[categoryId] ?? CATEGORIES[0];
  const others = category.words.filter((w) => w !== word);
  return others[Math.floor(Math.random() * others.length)] ?? word;
}

export const TOTAL_WORDS = CATEGORIES.reduce((sum, c) => sum + c.words.length, 0);
